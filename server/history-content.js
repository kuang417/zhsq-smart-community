/**
 * 生成某「时期 × 栏目」的专题正文。
 * 组合方式：时期概述 + 栏目要点 + 结合本栏目本时期的学习指引，
 * 因此 5×8=40 个组合均得到各自独立、可读的专题内容。
 */
export function buildHistoryContent(period, column) {
  const p = PERIOD_BODY[period] || ''
  const c = COL_BODY[column] || ''
  const lead = `【${period} · ${column}】`
  const note =
    `学习指引：请结合${period}的历史脉络，聚焦「${column}」专题，做到学史明理、学史增信、学史崇德、学史力行，` +
    '把学习成效转化为服务群众、参与基层治理的实际行动。'
  return [lead, '', p, '', c, '', note].join('\n')
}
